import { Router } from 'express';
import { login, signup } from '../controllers/authController.js';
import { cancelBooking, createBooking, listBookings } from '../controllers/bookingController.js';
import { createRoom, deleteRoom, listRooms } from '../controllers/roomController.js';
import { listUsers, updateUserRole } from '../controllers/userController.js';
import { createHotel, deleteHotel, listHotels, updateHotel } from '../controllers/hotelController.js';
import { adminOnly, authenticate } from '../middleware/auth.js';

const router = Router();
router.post('/auth/signup', signup);
router.post('/auth/login', login);
router.get('/rooms', listRooms);
router.get('/hotels', listHotels);
router.get('/bookings', authenticate, listBookings);
router.post('/bookings', authenticate, createBooking);
router.patch('/bookings/:id/cancel', authenticate, cancelBooking);
router.post('/admin/rooms', authenticate, adminOnly, createRoom);
router.get('/admin/rooms', authenticate, adminOnly, listRooms);
router.delete('/admin/rooms/:id', authenticate, adminOnly, deleteRoom);
router.get('/admin/hotels', authenticate, adminOnly, listHotels);
router.post('/admin/hotels', authenticate, adminOnly, createHotel);
router.patch('/admin/hotels/:id', authenticate, adminOnly, updateHotel);
router.delete('/admin/hotels/:id', authenticate, adminOnly, deleteHotel);
router.get('/admin/users', authenticate, adminOnly, listUsers);
router.patch('/admin/users/:id/role', authenticate, adminOnly, updateUserRole);
export default router;
